assert.deepEqual(catalog.parts,PARTS);assert.deepEqual(catalog.kinds,KINDS);
console.log('Vehicle AI context: original catalog, scoped read-only snapshots, attachment exclusion, AES notes, sample limits and current-vs-historical serial conflicts passed.');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PARTS,KINDS,newProject,addRecord} from '../../static/vehicle_tracker/js/vehicle-tracker-core.mjs';
import {reportProject} from '../../static/vehicle_tracker/js/vehicle-tracker-report.mjs';
import {buildSnapshot,fitRequest,SAMPLE_LIMIT} from '../../static/vehicle_tracker/js/vehicle-tracker-ai-context.mjs';

const project=reportProject(),before=structuredClone(project);
project.attachments.push({partId:'C1-LF-RF-PP',data:'data:private-attachment'});
project.references.push({data:'data:private-reference',hotspots:[]});
const snapshot=buildSnapshot(project,'C1-LF-RF-PP');
assert.equal(snapshot.records.length,1);assert.equal(snapshot.records[0].serial,'BZID009');
assert.equal(snapshot.summary.attachments,1);assert.equal(snapshot.summary.references,1);
assert.ok(!JSON.stringify(snapshot).includes('private-attachment'));assert.ok(!JSON.stringify(snapshot).includes('private-reference'));
assert.equal(buildSnapshot(project,'C1').records.every(row=>row.partId.startsWith('C1-')),true);
assert.equal(buildSnapshot(project,'C1-LF-RF-PP',{mode:'help'}).records.length,0);
assert.equal(buildSnapshot(project,'C1-LF-RF-PP',{mode:'help'}).current_records.length,0);
project.attachments.pop();project.references.pop();assert.deepEqual(project,before,'projection never changes project or backup data');
const all=buildSnapshot(project,'TRAIN');
assert.equal(all.summary.scope_records,285);assert.equal(all.records.length,SAMPLE_LIMIT);
assert.equal(all.audit.missing_records,4,'AES positions lack green-tag records, not an inferred failed inspection');
assert.equal(all.notes.filter(row=>row.notes.includes('AES')).length,4);
assert.equal(all.audit.duplicate_positions,0);
const large={question:'核对记录',mode:'audit',snapshot:structuredClone(all),history:Array.from({length:6},(_,i)=>({role:i%2?'assistant':'user',content:'说明'.repeat(1500)}))};
for(const row of [...large.snapshot.records,...large.snapshot.current_records])row.description='资料'.repeat(140);
const largeBefore=structuredClone(large),fitted=fitRequest(large);
assert.ok(new TextEncoder().encode(JSON.stringify(fitted)).length<=92*1024);
assert.deepEqual(large,largeBefore,'request fitting cannot mutate project-derived state or conversation');
assert.equal(fitted.snapshot.summary.scope_records,285,'full summary remains explicit when samples shrink');

const synthetic=newProject('current serial test');
addRecord(synthetic,'C1-LF-RF-PP',{wonum:'1001',serial:'shared',date:'2020-01-01'});
addRecord(synthetic,'C1-LF-RF-PP',{wonum:'1002',serial:'new',date:'2026-01-01'});
addRecord(synthetic,'C1-LF-RR-PP',{wonum:'1003',serial:'shared',date:'2020-01-01'});
assert.equal(buildSnapshot(synthetic,'TRAIN').audit.duplicate_positions,0,'old serial history must not appear as current conflict');
addRecord(synthetic,'C1-LF-RR-PP',{wonum:'1004',serial:'new',date:'2026-01-01'});
assert.equal(buildSnapshot(synthetic,'TRAIN').audit.duplicate_positions,2);
assert.equal(buildSnapshot(synthetic,'C1-LF-RF-PP').audit.duplicate_positions,0,'scope excludes the other position');
assert.throws(()=>buildSnapshot(project,'UNKNOWN'),/选择/);
